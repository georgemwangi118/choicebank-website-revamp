const links = [
  { href: '/admin', label: 'Dashboard', icon: DashboardIcon, exact: true },
  { href: '/admin/blog', label: 'Blog Posts', icon: ArticleIcon },
  { href: '/admin/jobs', label: 'Job Listings', icon: WorkIcon },
];

export default function AdminSidebar() {
  const pathname = usePathname();
  const router = useRouter();

  async function handleLogout() {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push('/admin/login');
    router.refresh();
  }

  return (
    <aside className="w-56 bg-[#0A0534] min-h-screen flex flex-col shrink-0">
      <div className="p-6 border-b border-white/10">
        <Image src={logo} alt="Choice Bank" height={32} className="brightness-0 invert" />
        <p className="text-white text-xs mt-1">Admin Portal</p>
      </div>
      <nav className="flex-1 p-4 space-y-1">
        {links.map(({ href, label, icon: Icon, exact }) => {
          const active = exact ? pathname === href : pathname.startsWith(href);
          return (
            <Link
              key={href}
              href={href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                active ? 'bg-white/10 text-white' : 'text-white/50 hover:text-white hover:bg-white/5'
              }`}
            >
              <Icon />
              {label}
            </Link>
          );
        })}
      </nav>
      <div className="p-4 border-t border-white/10">
        <button
          onClick={handleLogout}
          className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium text-white/50 hover:text-white hover:bg-white/5 transition-colors w-full"
        >
          <LogoutIcon />
          Sign Out
        </button>
      </div>
    </aside>
  );
}
